# OhMyMac — compiles src/sass into ready-to-install theme directories.
#
# Output layout (default: ${OHM_ROOT}/build):
#   OhMyMac-Light/ OhMyMac-Dark/
#     index.theme
#     gtk-3.0/gtk.css gtk-3.0/gtk-dark.css
#     gtk-4.0/gtk.css gtk-4.0/gtk-dark.css
#     gnome-shell/gnome-shell.css           (no base @import yet, see below)
#   libadwaita/gtk.css                      (for ~/.config/gtk-4.0/gtk.css)
#
# The Shell stylesheet is finalised at install time by shell_finalize(), which
# prepends an @import of the stock stylesheet present on the target system.

OHM_SRC="${OHM_ROOT}/src"
OHM_BUILD="${OHM_BUILD:-${OHM_ROOT}/build}"
OHM_VARIANTS=(Light Dark)

_sass_compiler() {
  if has sass && grep -qE '^1\.' <<<"$(sass --version 2>/dev/null)"; then
    echo dart
  elif has sassc; then
    echo sassc
  else
    return 1
  fi
}

# sass_compile <input.scss> <output.css>
sass_compile() {
  local in="$1" out="$2" compiler
  compiler="$(_sass_compiler)" || die "No Sass compiler found (install sassc or dart-sass)."
  mkdir -p "$(dirname "${out}")"
  case "${compiler}" in
    dart)
      sass --no-source-map --style=expanded --quiet-deps \
        --silence-deprecation=import --silence-deprecation=global-builtin \
        "${in}" "${out}"
      ;;
    sassc)
      sassc --style expanded "${in}" "${out}"
      ;;
  esac
}

write_index_theme() {
  local variant="$1" dir="$2" icons cursor
  if [[ "${variant}" == Dark ]]; then icons="MacTahoe-dark"; else icons="MacTahoe-light"; fi
  cursor="macOS"
  cat >"${dir}/index.theme" <<EOF
[Desktop Entry]
Type=X-GNOME-Metatheme
Name=OhMyMac-${variant}
Comment=macOS-inspired theme for GNOME (${variant,,})
Encoding=UTF-8

[X-GNOME-Metatheme]
GtkTheme=OhMyMac-${variant}
MetacityTheme=OhMyMac-${variant}
IconTheme=${icons}
CursorTheme=${cursor}
ButtonLayout=close,minimize,maximize:
EOF
}

build_themes() {
  local out="${1:-${OHM_BUILD}}" variant lower dir tmp
  log_step "Building stylesheets ($(_sass_compiler 2>/dev/null || echo 'no compiler'))"

  rm -rf "${out}"
  tmp="${out}/.tmp"
  mkdir -p "${tmp}"

  sass_compile "${OHM_SRC}/sass/gtk3/gtk.scss"      "${tmp}/gtk3-light.css"
  sass_compile "${OHM_SRC}/sass/gtk3/gtk-dark.scss" "${tmp}/gtk3-dark.css"
  sass_compile "${OHM_SRC}/sass/gtk4/gtk.scss"      "${tmp}/gtk4.css"
  sass_compile "${OHM_SRC}/sass/gnome-shell/gnome-shell-light.scss" "${tmp}/shell-light.css"
  sass_compile "${OHM_SRC}/sass/gnome-shell/gnome-shell-dark.scss"  "${tmp}/shell-dark.css"

  for variant in "${OHM_VARIANTS[@]}"; do
    lower="${variant,,}"
    dir="${out}/OhMyMac-${variant}"
    mkdir -p "${dir}/gtk-3.0" "${dir}/gtk-4.0" "${dir}/gnome-shell"

    write_index_theme "${variant}" "${dir}"

    # GTK 3: gtk.css follows the variant; gtk-dark.css is used by apps that
    # request a dark theme (e.g. image viewers) regardless of variant.
    cp "${tmp}/gtk3-${lower}.css" "${dir}/gtk-3.0/gtk.css"
    cp "${tmp}/gtk3-dark.css"     "${dir}/gtk-3.0/gtk-dark.css"

    # GTK 4 without libadwaita: stock "Default" theme + OhMyMac tokens.
    {
      printf '@import url("resource:///org/gtk/libgtk/theme/Default/Default-%s.css");\n' "${lower}"
      cat "${tmp}/gtk4.css"
    } >"${dir}/gtk-4.0/gtk.css"
    {
      printf '@import url("resource:///org/gtk/libgtk/theme/Default/Default-dark.css");\n'
      cat "${tmp}/gtk4.css"
    } >"${dir}/gtk-4.0/gtk-dark.css"

    cp "${tmp}/shell-${lower}.css" "${dir}/gnome-shell/gnome-shell.css"
  done

  mkdir -p "${out}/libadwaita"
  {
    printf '/* OhMyMac %s — managed file, regenerated by install.sh. */\n' "${OHM_VERSION}"
    cat "${tmp}/gtk4.css"
  } >"${out}/libadwaita/gtk.css"

  rm -rf "${tmp}"
  log_ok "Stylesheets built in ${out/#${OHM_ROOT}\//}"
}

# --- Shell base stylesheet ---------------------------------------------------

# Prints the resource path of the stock Shell stylesheet for a variant.
# GNOME 47–48 ship gnome-shell-{light,dark}.css; GNOME 49+ (incl. 51) ship
# only gnome-shell-dark.css, and releases before 47 a single gnome-shell.css.
# OhMyMac's light variant then layers its light colours over the dark base.
shell_base_resource() {
  local variant="${1,,}" gresource="${OHM_SHELL_GRESOURCE:-/usr/share/gnome-shell/gnome-shell-theme.gresource}"
  local list="" candidate prefix="/org/gnome/shell/theme"
  if [[ -r "${gresource}" ]] && has gresource; then
    list="$(gresource list "${gresource}" 2>/dev/null || true)"
  fi

  if [[ -n "${list}" ]]; then
    for candidate in "gnome-shell-${variant}.css" gnome-shell-dark.css gnome-shell.css; do
      if grep -qx "${prefix}/${candidate}" <<<"${list}"; then
        echo "resource://${prefix}/${candidate}"
        return 0
      fi
    done
  fi
  # No gresource tool: decide by version.
  if (( OHM_GNOME_MAJOR > 0 && OHM_GNOME_MAJOR < 47 )); then
    echo "resource://${prefix}/gnome-shell.css"
  elif (( OHM_GNOME_MAJOR >= 49 || OHM_GNOME_MAJOR == 0 )); then
    echo "resource://${prefix}/gnome-shell-dark.css"
  else
    echo "resource://${prefix}/gnome-shell-${variant}.css"
  fi
}

# shell_finalize <theme-dir> <variant> — prepends the stock @import.
shell_finalize() {
  local dir="$1" variant="$2" css base
  css="${dir}/gnome-shell/gnome-shell.css"
  [[ -f "${css}" ]] || return 0
  grep -q '^@import url("resource:///org/gnome/shell/theme/' "${css}" && return 0
  base="$(shell_base_resource "${variant}")"
  {
    printf '/* OhMyMac %s for GNOME Shell — base: %s */\n' "${OHM_VERSION}" "${base}"
    printf '@import url("%s");\n\n' "${base}"
    cat "${css}"
  } >"${css}.new"
  mv -f "${css}.new" "${css}"
}
